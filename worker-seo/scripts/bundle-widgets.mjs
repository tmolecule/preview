/**
 * Inline the built widget IIFE bundles into src/widget-bundles.js so the Worker
 * can serve them with no external asset hosting (mirrors WhollyKaw's approach).
 *
 *   1. cd ../widgets && npm run build      # emits widgets/dist/<name>.js
 *   2. node scripts/bundle-widgets.mjs     # regenerates src/widget-bundles.js
 *   3. wrangler deploy
 *
 * The JS is embedded via JSON.stringify so any character (backticks, ${}) is
 * safe. WIDGET_VERSION is a content hash used to bust the <script> cache when a
 * widget changes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(here, '../widgets/dist');
const outFile = resolve(here, '../src/widget-bundles.js');

// name -> exported constant. Add a line per widget as each ships.
const WIDGETS = {
  'brew-guide': 'BREW_GUIDE_JS',
  'cost-per-cup': 'COST_PER_CUP_JS',
  'tea-finder': 'TEA_FINDER_JS',
  'caffeine-comparator': 'CAFFEINE_COMPARATOR_JS',
  'collagen-calculator': 'COLLAGEN_CALCULATOR_JS',
  'sugar-saved': 'SUGAR_SAVED_JS',
  'spice-blend-builder': 'SPICE_BLEND_BUILDER_JS',
  'advisor': 'ADVISOR_JS',
  'steep-guide': 'STEEP_GUIDE_JS',
};

const parts = [];
const hash = createHash('sha256');
const exportsList = [];

for (const [name, constName] of Object.entries(WIDGETS)) {
  const js = readFileSync(resolve(distDir, `${name}.js`), 'utf8');
  hash.update(js);
  parts.push(`export const ${constName} = ${JSON.stringify(js)};`);
  exportsList.push(constName);
}

const version = hash.digest('hex').slice(0, 8);

const banner = `// AUTO-GENERATED by scripts/bundle-widgets.mjs — do not edit by hand.
// Regenerate after \`cd ../widgets && npm run build\`.
export const WIDGET_VERSION = ${JSON.stringify(version)};
`;

writeFileSync(outFile, banner + '\n' + parts.join('\n') + '\n');
console.log(`wrote ${outFile}`);
console.log(`  WIDGET_VERSION = ${version}`);
console.log(`  exports: ${exportsList.join(', ')}`);
